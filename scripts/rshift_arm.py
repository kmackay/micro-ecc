#!/usr/bin/env python3
"""Generates asm_arm_rshift.inc: unrolled uECC_vli_rshift1 for ARM (5..8 words).

Thumb-2 / ARM: load all words with one ldm, shift the top word with lsrs and
rotate the carry down through the rest with rrxs, then store with one stm.
Uses r1-r6, r12 and lr (never r7 / r11, so frame pointers are not disturbed).

Thumb-1: no rrx, so each word is combined with the low bit of the word above:
w[i] = (w[i] >> 1) | (w[i + 1] << 31), streaming upwards with ldr / str.
Uses r1-r3 only.
"""
import sys

out = []
def emit(s=""):
    out.append(s)

T2_REGS = ["r1", "r2", "r3", "r4", "r5", "r6", "r12", "lr"]

def t2_rshift(n):
    regs = T2_REGS[:n - 1] + ["lr"] if n < 8 else T2_REGS
    rl = "{" + ", ".join(regs) + "}"
    lines = [f"ldmia r0, {rl}", f"lsrs {regs[-1]}, {regs[-1]}, #1"]
    for r in reversed(regs[:-1]):
        lines.append(f"rrxs {r}, {r}")
    lines.append(f"stmia r0, {rl}")
    return lines

def t1_rshift(n):
    a, b, t = "r1", "r2", "r3"
    lines = [f"ldr {a}, [r0]"]
    for i in range(n - 1):
        lines += [f"ldr {b}, [r0, #{4 * (i + 1)}]",
                  f"lsrs {a}, {a}, #1",
                  f"lsls {t}, {b}, #31",
                  f"orrs {a}, {t}",
                  f"str {a}, [r0, #{4 * i}]"]
        a, b = b, a
    lines += [f"lsrs {a}, {a}, #1", f"str {a}, [r0, #{4 * (n - 1)}]"]
    return lines

SIZES = [(8, "(uECC_SUPPORTS_secp256r1 || uECC_SUPPORTS_secp256k1)"),
         (7, "uECC_SUPPORTS_secp224r1"),
         (6, "(uECC_SUPPORTS_secp160r1 || uECC_SUPPORTS_secp192r1)"),
         (5, "uECC_SUPPORTS_secp160r1")]

def func(gen, thumb1):
    emit("uECC_VLI_API void uECC_vli_rshift1(uECC_word_t *vli, wordcount_t num_words) {")
    emit('    register uECC_word_t *r0 __asm__("r0") = vli;')
    for n, cond in SIZES:
        emit(f"#if {cond}")
        emit(f"#if (uECC_MIN_WORDS < {n})")
        emit(f"    if (num_words == {n})")
        emit("#endif")
        emit("    {")
        emit("        __asm__ volatile (")
        emit('            ".syntax unified \\n\\t"')
        for l in gen(n):
            emit(f'            "{l} \\n\\t"')
        emit("            RESUME_SYNTAX")
        emit('            : "+l" (r0)' if thumb1 else '            : "+r" (r0)')
        emit("            :")
        if thumb1:
            emit('            : "r1", "r2", "r3", "cc", "memory"')
        else:
            emit('            : "r1", "r2", "r3", "r4", "r5", "r6", "r12", "lr", "cc", "memory"')
        emit("        );")
        emit("        return;")
        emit("    }")
        emit("#endif")
    emit("}")
    emit("#define asm_rshift1 1")
    emit("")

emit("/* Copyright 2015, Kenneth MacKay. Licensed under the BSD 2-clause license. */")
emit("")
emit("/* Unrolled uECC_vli_rshift1 for ARM. Generated by scripts/rshift_arm.py. The")
emit("   smallest supported size (uECC_MIN_WORDS) is handled unconditionally as the")
emit("   last case. */")
emit("")
emit("#ifndef _UECC_ASM_ARM_RSHIFT_H_")
emit("#define _UECC_ASM_ARM_RSHIFT_H_")
emit("")
emit("#if (uECC_PLATFORM == uECC_arm_thumb)")
emit("")
func(t1_rshift, True)
emit("#else /* Thumb-2 or 32-bit ARM */")
emit("")
func(t2_rshift, False)
emit("#endif /* uECC_PLATFORM == uECC_arm_thumb */")
emit("")
emit("#endif /* _UECC_ASM_ARM_RSHIFT_H_ */")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
